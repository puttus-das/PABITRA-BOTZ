import { Module } from "../lib/plugins.js";
import { proto, getContentType } from "baileys";

const isOwner = (message) => !!(message?.isfromMe || message?.isFromMe);
const withTimeout = (promise, ms) => Promise.race([
  promise,
  new Promise((_, reject) => setTimeout(() => reject(new Error("timeout")), ms)),
]);

const BIZ_NODES = [{
  tag: "biz",
  attrs: {},
  content: [{
    tag: "interactive",
    attrs: { type: "native_flow", v: "1" },
    content: [{ tag: "native_flow", attrs: { v: "9", name: "mixed" } }],
  }],
}];

function buildReplayFile(quoted) {
  const content = typeof quoted.msg === "string"
    ? { conversation: quoted.msg }
    : { [quoted.type]: quoted.msg };
  if (content.interactiveMessage) {
    content.messageContextInfo = { deviceListMetadata: {}, deviceListMetadataVersion: 2 };
  }
  const message = proto.Message.toObject(proto.Message.create(content), { bytes: String, longs: Number });
  const hasButtons = !!(message.interactiveMessage?.nativeFlowMessage || message.buttonsMessage);
  const options = hasButtons ? { additionalNodes: BIZ_NODES } : {};
  return "// Generated by Pabitra-Bot .crm — data-only message replay file.\n" +
    "// Reply to this file with .run to send the message again.\n" +
    "=> conn.relayMessage(\n  m.chat,\n" +
    `${JSON.stringify(message, null, 2)},\n${JSON.stringify(options, null, 2)}\n)`;
}

Module({
  command: "crm",
  aliases: ["inspect", "msginfo"],
  package: "tools",
  description: "Show message information and create a replay file — owner only",
  usage: ".crm (reply to a message)",
})(async (message) => {
  try {
    if (!isOwner(message)) return message.send("_This command is for the owner only_");
    const quoted = message.quoted;
    const info = {
      type: quoted ? quoted.type : getContentType(message.raw?.message) || "unknown",
      chat: message.from,
      group: !!message.isGroup,
      id: (quoted ? quoted.id : message.id) || null,
      sender: (quoted ? quoted.participant : message.sender) || null,
      fromMe: quoted ? !!quoted.fromMe : true,
      text: ((quoted ? quoted.body : message.body) || "").slice(0, 200),
    };
    await message.send(
      `*📋 Message Info*${quoted ? " _(replied message)_" : ""}\n\n` +
      `• Type   : ${info.type}\n• Chat   : ${info.chat}\n• Group  : ${info.group ? "yes" : "no"}\n` +
      `• ID     : ${info.id || "n/a"}\n• Sender : ${info.sender || "n/a"}\n` +
      `• FromMe : ${info.fromMe ? "yes" : "no"}\n• Text   : ${info.text || "(none)"}`
    );
    if (!quoted) return;
    const file = buildReplayFile(quoted);
    await withTimeout(message.conn.sendMessage(message.from, {
      document: Buffer.from(file, "utf8"),
      mimetype: "application/javascript",
      fileName: `${String(info.type).replace(/[^\w.-]/g, "") || "Message"}.js`,
    }), 25_000);
  } catch (error) {
    console.error("[CRM]", error?.message || error);
    await message.send(`⚠️ Error: ${error?.message || "unknown"}`);
  }
});
