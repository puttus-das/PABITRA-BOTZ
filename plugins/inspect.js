import fs from "fs";
import { Module } from "../lib/plugins.js";
import { proto, getContentType, generateWAMessageFromContent } from "baileys";

const isOwner = (m) => !!(m.isfromMe || m.isFromMe);
const withTimeout = (p, ms) =>
  Promise.race([p, new Promise((_, rej) => setTimeout(() => rej(new Error("timeout")), ms))]);

// WhatsApp needs this extra node to render button / native-flow messages sent from a normal account
const BIZ_NODES = [
  {
    tag: "biz",
    attrs: {},
    content: [
      {
        tag: "interactive",
        attrs: { type: "native_flow", v: "1" },
        content: [{ tag: "native_flow", attrs: { v: "9", name: "mixed" } }],
      },
    ],
  },
];

// ── build the replay file ─────────────────────────────────────────────────────
// "=> conn.relayMessage(m.chat, <message JSON>, <options JSON>)"
// It is DATA ONLY — .run reads the two JSON blocks back; no code is ever executed.
function buildReplayFile(q) {
  const content =
    typeof q.msg === "string" ? { conversation: q.msg } : { [q.type]: q.msg };
  if (content.interactiveMessage) {
    content.messageContextInfo = { deviceListMetadata: {}, deviceListMetadataVersion: 2 };
  }
  // proto → plain JSON (bytes become base64 strings)
  const obj = proto.Message.toObject(proto.Message.create(content), {
    bytes: String,
    longs: Number,
  });
  const hasButtons = !!(obj.interactiveMessage?.nativeFlowMessage || obj.buttonsMessage);
  const options = hasButtons ? { additionalNodes: BIZ_NODES } : {};
  return (
    `// Generated by Pabitra-Bot .crm — message replay file (data only).\n` +
    `// Reply to this file with .run to send the message again.\n` +
    `=> conn.relayMessage(\n  m.chat,\n${JSON.stringify(obj, null, 2)},\n${JSON.stringify(options, null, 2)}\n)`
  );
}

function parseReplayFile(text) {
  const start = text.indexOf("=> conn.relayMessage(");
  if (start === -1) throw new Error("not a .crm replay file");
  let rest = text.slice(start + "=> conn.relayMessage(".length).trim();
  rest = rest.replace(/\)\s*$/, "").trim(); // closing ")"
  rest = rest.replace(/^m\.chat\s*,/, "").trim(); // "m.chat,"
  const arr = JSON.parse(`[${rest}]`); // [message, options]
  if (!arr[0] || typeof arr[0] !== "object") throw new Error("replay file is empty");
  return { message: arr[0], options: arr[1] || {} };
}

// ── .crm ─ message info (+ replay file when you reply to a message) ───────────
Module({
  command: "crm",
  aliases: ["inspect", "msginfo"],
  package: "tools",
  description: "Message info + replay .js file — owner only, reply to a message",
})(async (message) => {
  try {
    if (!isOwner(message)) return message.send("_This command is for the owner only_");

    const q = message.quoted;
    const info = {
      type: q ? q.type : getContentType(message.raw?.message) || "unknown",
      chat: message.from,
      group: !!message.isGroup,
      id: (q ? q.id : message.id) || null,
      sender: (q ? q.participant : message.sender) || null,
      fromMe: q ? !!q.fromMe : true,
      text: ((q ? q.body : message.body) || "").slice(0, 200),
    };

    await message.send(
      `*📋 Message Info*${q ? " _(replied message)_" : ""}\n\n` +
        `• Type   : ${info.type}\n` +
        `• Chat   : ${info.chat}\n` +
        `• Group  : ${info.group ? "yes" : "no"}\n` +
        `• ID     : ${info.id || "n/a"}\n` +
        `• Sender : ${info.sender || "n/a"}\n` +
        `• FromMe : ${info.fromMe ? "yes" : "no"}\n` +
        `• Text   : ${info.text || "(none)"}`
    );

    if (!q) return; // nothing to replay

    let file;
    try {
      file = buildReplayFile(q);
    } catch (e) {
      console.error("[CRM] replay build failed:", e?.message || e);
      return;
    }
    try {
      await withTimeout(
        message.conn.sendMessage(message.from, {
          document: Buffer.from(file, "utf8"),
          mimetype: "application/javascript",
          fileName: `${String(info.type).replace(/[^\w.-]/g, "") || "Message"}.js`,
        }),
        25_000
      );
    } catch (e) {
      console.error("[CRM] file not sent:", e?.message || e);
    }
  } catch (err) {
    console.error("[CRM]", err?.message || err);
    await message.send(`⚠️ Error: ${err?.message || "unknown"}`);
  }
});

// ── .run ─ send the message from a .crm replay file again ─────────────────────
// Safety: owner only · file must come from THIS account · max 300 KB · data only (no code runs)
Module({
  command: "run",
  package: "tools",
  description: "Re-send the message stored in a .crm file — owner only, reply to the file",
})(async (message) => {
  try {
    if (!isOwner(message)) return message.send("_This command is for the owner only_");

    const q = message.quoted;
    if (!q || q.type !== "documentMessage") return message.send("_Reply to a .crm .js file with .run_");

    const fileName = q.msg?.fileName || "file.js";
    if (!/\.m?js$/i.test(fileName)) return message.send("_Only .js files from .crm can be run_");
    if (!q.fromMe) {
      return message.send("⛔ For safety I only run files sent from this account.");
    }
    if (Number(q.msg?.fileLength || 0) > 300 * 1024) return message.send("_File too large (max 300 KB)_");

    const buf = await q.download();
    if (!buf?.length) return message.send("⚠️ Could not download the file");

    const { message: msgObj, options } = parseReplayFile(buf.toString("utf8"));
    const content = proto.Message.fromObject(msgObj);
    const wa = generateWAMessageFromContent(message.from, content, {
      userJid: message.conn.user?.id,
    });
    await message.conn.relayMessage(message.from, wa.message, {
      messageId: wa.key.id,
      ...(options.additionalNodes ? { additionalNodes: options.additionalNodes } : {}),
    });

    await message.send(`✅ ${fileName} ran successfully.`);
  } catch (err) {
    console.error("[RUN]", err?.message || err);
    await message.send(`❌ ${err?.message || "run failed"}`);
  }
});
